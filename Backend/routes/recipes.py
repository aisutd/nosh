@router.get("/recipes/saved")
async def get_saved_recipes(current_user: dict = Depends(get_current_user)):
    ids = []
    for rid in current_user.get("saved_recipes", []):
        try:
            ids.append(rid if rid.startswith("rag:") else ObjectId(rid))
        except InvalidId:
            pass
    recipes = await collection.find({"_id": {"$in": ids}}).to_list(length=200)
    return recipes_list(recipes)

class SaveContext(BaseModel):
    ingredients: list[str]
    user_query: str = ""


def load_rag_source(recipe_id):
    source_id = recipe_id.removeprefix("rag:")
    # IDs generated by this project's index are SHA-256 hashes.
    if len(source_id) != 64 or any(c not in "0123456789abcdef" for c in source_id):
        raise HTTPException(status_code=400, detail="Invalid recipe id")
    result = get_collection().get(ids=[source_id], include=["documents", "metadatas"])
    if not result["ids"]:
        raise HTTPException(status_code=404, detail="Recipe not found")
    meta = result["metadatas"][0] or {}
    return {"_id": recipe_id, "kind": "rag", "rag_source_id": source_id,
            "title": meta.get("recipe_name", "Untitled"),
            "ingredients": [i.strip() for i in meta.get("ingredients", "").split(",") if i.strip()],
            "directions": [i.strip() for i in meta.get("directions", "").splitlines() if i.strip()],
            "link": meta.get("url", ""), "image": meta.get("img_src"), "ner": []}


# Save MongoDB recipes or persist a RAG source with the user's reviewed pantry.
@router.post("/recipes/save/{recipe_id}")
async def save_recipe(recipe_id: str, context: SaveContext | None = None,
                      current_user: dict = Depends(get_current_user)):
    update = {"$addToSet": {"saved_recipes": recipe_id}}
    if recipe_id.startswith("rag:"):
        if context is None or not any(name.strip() for name in context.ingredients):
            raise HTTPException(status_code=400, detail="Reviewed ingredients are required to save this recipe.")
        source = await run_in_threadpool(load_rag_source, recipe_id)
        await collection.update_one({"_id": recipe_id}, {"$setOnInsert": source}, upsert=True)
        update["$set"] = {f"rag_contexts.{source['rag_source_id']}": context.model_dump()}
    else:
        try:
            oid = ObjectId(recipe_id)
        except InvalidId:
            raise HTTPException(status_code=400, detail="Invalid recipe id")
        if not await collection.find_one({"_id": oid}):
            raise HTTPException(status_code=404, detail="Recipe not found")
    await user.update_one({"_id": current_user["_id"]}, update)
    doc = await user.find_one({"_id": current_user["_id"]}, {"saved_recipes": 1})
    return {"saved": doc.get("saved_recipes", [])}


@router.post("/recipes/saved-generate/{recipe_id}")
async def generate_saved_recipe(recipe_id: str, current_user: dict = Depends(get_current_user)):
    if recipe_id not in current_user.get("saved_recipes", []) or not recipe_id.startswith("rag:"):
        raise HTTPException(status_code=404, detail="Saved recipe not found")
    source_id = recipe_id.removeprefix("rag:")
    context = current_user.get("rag_contexts", {}).get(source_id)
    if not context:
        raise HTTPException(status_code=409, detail="Please search and save this recipe again to include your pantry.")
    try:
        result = await run_in_threadpool(run_nosh, context["ingredients"],
            user_query=context.get("user_query", ""), selected_recipe_id=source_id)
    except Exception as exc:
        raise HTTPException(status_code=503, detail="Recipe generation is unavailable. Check Ollama and the recipe index.") from exc
    return {"result": result}

# Unsave a recipe
@router.post("/recipes/unsave/{recipe_id}")
async def unsave_recipe(recipe_id: str, current_user: dict = Depends(get_current_user)):
    await user.update_one({"_id": current_user["_id"]}, {"$pull": {"saved_recipes": recipe_id}})
    doc = await user.find_one({"_id": current_user["_id"]}, {"saved_recipes": 1})
    return {"saved": doc.get("saved_recipes", [])}

# Public: browse recipes without logging in (used by the landing page and Swipe)
@router.get("/recipes/browse")
async def browse_recipes(limit: int = 10, skip: int = 0):
    limit = min(limit, 30)    # cap it so nobody can pull the whole database
    docs = await collection.find({}).skip(skip).limit(limit).to_list(length=limit)   # skip = pagination offset
    return recipes_list(docs)

# Get one recipe by id (used by the Cook page). Keep this LAST, otherwise it catches
# /recipes/saved and /recipes/browse as if they were ids
@router.get("/recipes/{recipe_id}")
async def get_recipe(recipe_id: str):
    try:
        oid = recipe_id if recipe_id.startswith("rag:") else ObjectId(recipe_id)
    except InvalidId:
        raise HTTPException(status_code=404, detail="Recipe not found")
    doc = await collection.find_one({"_id": oid})
    if not doc:
        raise HTTPException(status_code=404, detail="Recipe not found")
    return recipe_data(doc)

